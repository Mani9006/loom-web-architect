// Type exports for TypeScript usage
export type JobRole = typeof JOB_ROLES[number];
export type CommonSkill = typeof COMMON_SKILLS[number];

// Helper function to get roles by category
export function getJobRolesByCategory(category: string): readonly string[] {
  const categoryMap: Record<string, readonly string[]> = {
    "software-engineering": softwareEngineeringRoles,
    "data-ai": dataAndAIRoles,
    "product-design": productAndDesignRoles,
    "business-operations": businessAndOperationsRoles,
    "marketing-content": marketingAndContentRoles,
    "finance-accounting": financeAndAccountingRoles,
    "hr-recruiting": hrAndRecruitingRoles,
    "sales": salesRoles,
    "customer-success": customerSuccessRoles,
    "healthcare": healthcareRoles,
    "other": otherRoles,
  };

  return categoryMap[category.toLowerCase()] || [];
}

// Helper function to get skills by category
export function getSkillsByCategory(category: string): readonly string[] {
  const categoryMap: Record<string, readonly string[]> = {
    "programming-languages": programmingLanguages,
    "frontend": frontendSkills,
    "backend": backendSkills,
    "cloud-infrastructure": cloudAndInfrastructureSkills,
    "database": databaseSkills,
    "ai-ml": aiAndMLSkills,
    "design": designSkills,
    "business-productivity": businessProductivitySkills,
    "security-compliance": securityAndComplianceSkills,
    "soft-skills": softSkills,
  };

  return categoryMap[category.toLowerCase()] || [];
}

// Helper function to search for roles
export function searchJobRoles(query: string): JobRole[] {
  const lowerQuery = query.toLowerCase();
  return JOB_ROLES.filter((role) => role.toLowerCase().includes(lowerQuery)) as JobRole[];
}

// Helper function to search for skills
export function searchSkills(query: string): CommonSkill[] {
  const lowerQuery = query.toLowerCase();
  return COMMON_SKILLS.filter((skill) => skill.toLowerCase().includes(lowerQuery)) as CommonSkill[];
}
