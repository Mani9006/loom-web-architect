-- Auto-apply trust boundary.
--
-- Queue mutation and worker RPCs are service-owned. Signed-in users can
-- observe their own progress, but enqueue/cancel/complete only through the
-- entitlement-checked Edge Functions.

REVOKE EXECUTE ON FUNCTION public.claim_applypass_task(text) FROM PUBLIC, anon, authenticated;
REVOKE EXECUTE ON FUNCTION public.append_applypass_task_log(uuid, jsonb) FROM PUBLIC, anon, authenticated;
REVOKE EXECUTE ON FUNCTION public.increment_ai_usage(uuid, text, integer, integer) FROM PUBLIC, anon, authenticated;
REVOKE EXECUTE ON FUNCTION public.reap_stale_applypass_tasks() FROM PUBLIC, anon, authenticated;
REVOKE EXECUTE ON FUNCTION public.reset_agent_action_counters() FROM PUBLIC, anon, authenticated;

GRANT EXECUTE ON FUNCTION public.claim_applypass_task(text) TO service_role;
GRANT EXECUTE ON FUNCTION public.append_applypass_task_log(uuid, jsonb) TO service_role;
GRANT EXECUTE ON FUNCTION public.increment_ai_usage(uuid, text, integer, integer) TO service_role;
GRANT EXECUTE ON FUNCTION public.reap_stale_applypass_tasks() TO service_role;
GRANT EXECUTE ON FUNCTION public.reset_agent_action_counters() TO service_role;

ALTER FUNCTION public.claim_applypass_task(text) SET search_path = pg_catalog, public;
ALTER FUNCTION public.append_applypass_task_log(uuid, jsonb) SET search_path = pg_catalog, public;

DROP POLICY IF EXISTS "Users can create their own applypass tasks" ON public.applypass_tasks;
DROP POLICY IF EXISTS "Users can update their own applypass tasks" ON public.applypass_tasks;
REVOKE INSERT, UPDATE, DELETE ON public.applypass_tasks FROM PUBLIC, anon, authenticated;
GRANT SELECT ON public.applypass_tasks TO authenticated;
GRANT ALL ON public.applypass_tasks TO service_role;

-- Draft rows are generated by the tailoring service. The only direct client
-- mutation retained is a truthful ready -> submitted acknowledgement after a
-- user completes an external/manual application.
DROP POLICY IF EXISTS "Users manage own drafts" ON public.draft_applications;
DROP POLICY IF EXISTS "Users read own drafts" ON public.draft_applications;
DROP POLICY IF EXISTS "Users acknowledge manual draft submission" ON public.draft_applications;

CREATE POLICY "Users read own drafts"
  ON public.draft_applications
  FOR SELECT
  TO authenticated
  USING ((SELECT auth.uid()) = user_id);

CREATE POLICY "Users acknowledge manual draft submission"
  ON public.draft_applications
  FOR UPDATE
  TO authenticated
  USING ((SELECT auth.uid()) = user_id AND status = 'ready')
  WITH CHECK (
    (SELECT auth.uid()) = user_id
    AND status = 'submitted'
    AND submitted_at IS NOT NULL
  );

REVOKE INSERT, UPDATE, DELETE ON public.draft_applications FROM PUBLIC, anon, authenticated;
GRANT SELECT ON public.draft_applications TO authenticated;
GRANT UPDATE (status, submitted_at) ON public.draft_applications TO authenticated;
GRANT ALL ON public.draft_applications TO service_role;

-- Audit entries are service-generated. Letting arbitrary signed-in clients
-- choose action/resource/tenant metadata permits audit-trail forgery/flooding.
REVOKE EXECUTE ON FUNCTION public.write_audit_log(uuid, text, text, text, uuid, jsonb, text, text)
  FROM PUBLIC, anon, authenticated;
GRANT EXECUTE ON FUNCTION public.write_audit_log(uuid, text, text, text, uuid, jsonb, text, text)
  TO service_role;

-- has_role is required by RLS policies. Bind signed-in callers to their own
-- identity so the exposed RPC cannot enumerate another user's roles.
CREATE OR REPLACE FUNCTION public.has_role(_user_id uuid, _role public.app_role)
RETURNS boolean
LANGUAGE sql
STABLE
SECURITY DEFINER
SET search_path = pg_catalog, public
AS $$
  SELECT EXISTS (
    SELECT 1
    FROM public.user_roles
    WHERE user_id = COALESCE((SELECT auth.uid()), _user_id)
      AND role = _role
  )
$$;

REVOKE EXECUTE ON FUNCTION public.has_role(uuid, public.app_role) FROM PUBLIC, anon;
GRANT EXECUTE ON FUNCTION public.has_role(uuid, public.app_role) TO authenticated, service_role;

